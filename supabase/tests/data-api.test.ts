function localSql(statement: string) {
  execFileSync('docker', [
    '--host', 'unix:///var/run/docker.sock', 'exec', '-i', databaseContainer,
    'psql', '-XqAt', '-U', 'postgres', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1',
  ], { input: statement, stdio: ['pipe', 'pipe', 'pipe'] })
}

function sqlUuid(id: string) {
  assert.match(id, /^[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}$/)
  return `'${id}'::uuid`
}

function requireSuccess(error: { code?: string } | null, action: string) {
  assert.ok(!error, error?.code ? `${action} failed (${error.code}).` : action)
}

async function createAccount(t: TestContext) {
  const email = `wallflow-${randomUUID()}@example.com`
  const password = randomBytes(24).toString('base64url')
  const created = await admin.auth.admin.createUser({ email, password, email_confirm: true })
  requireSuccess(created.error, 'Create synthetic local Auth account')
  assert.ok(created.data.user)
  const id = created.data.user.id
  t.after(async () => requireSuccess((await admin.auth.admin.deleteUser(id)).error, 'Remove synthetic test account'))
  const client = testClient()
  const login = await client.auth.signInWithPassword({ email, password })
  requireSuccess(login.error, 'Sign in through local Auth')
  assert.ok(login.data.session)
  assert.equal(login.data.session.user.id, id)
  return { id, client, auth: createSupabaseAuthApi(client), workspace: createSupabaseWorkspaceApi(client), email, password }
}

